const esbuild = require("esbuild");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const check = process.argv.includes("--check");
const watch = process.argv.includes("--watch");

// Every UI surface is authored under ui/ and compiled into the classic scripts
// the extension manifest loads. Page UIs (options/popup) bundle React per page.
// In-page UIs share one vendor bundle so a YouTube page with subtitles, the
// selection toolbar and immersive translation still parses React only once.
const targets = [
    {
        name: "options",
        entry: "ui/options/main.jsx",
        outfile: "options/options.js",
        jsx: "automatic",
    },
    {
        name: "popup",
        entry: "ui/popup/main.jsx",
        outfile: "popup/popup.js",
        jsx: "automatic",
    },
    {
        name: "React vendor",
        entry: "ui/content/vendor.js",
        outfile: "src/ui/react-vendor.js",
        jsx: "automatic",
    },
    {
        name: "in-page React UI",
        entry: "ui/content/index.js",
        outfile: "src/ui/content-ui.js",
        // The vendor bundle owns the React instance; JSX compiles against that
        // same copy instead of importing a second react/jsx-runtime.
        jsx: "transform",
        jsxFactory: "React.createElement",
        jsxFragment: "React.Fragment",
        loader: {".css": "text"},
    },
];

const banner = {js: "// Generated by npm run build. Edit ui/ sources instead."};

function buildOptions(target, write) {
    return {
        absWorkingDir: root,
        entryPoints: [target.entry],
        outfile: target.outfile,
        bundle: true,
        write,
        format: "iife",
        jsx: target.jsx,
        jsxFactory: target.jsxFactory,
        jsxFragment: target.jsxFragment,
        loader: target.loader,
        target: ["chrome110", "firefox140"],
        define: {"process.env.NODE_ENV": '"production"'},
        minify: true,
        legalComments: "eof",
        charset: "utf8",
        banner,
    };
}

async function build() {
    for (const target of targets) {
        if (watch) {
            const context = await esbuild.context(buildOptions(target, false));
            await context.watch();
        } else {
            const result = await esbuild.build(buildOptions(target, false));
            for (const file of result.outputFiles) {
                if (check) {
                    if (
                        !fs.existsSync(file.path) ||
                        !fs.readFileSync(file.path).equals(Buffer.from(file.contents))
                    )
                        throw new Error(
                            `Stale bundle: ${path.relative(root, file.path)}. Run npm run build.`,
                        );
                } else {
                    fs.mkdirSync(path.dirname(file.path), {recursive: true});
                    fs.writeFileSync(file.path, file.contents);
                }
            }
        }
    }
    console.log(
        watch
            ? "Watching React UI sources…"
            : check
                ? "UI bundles match their sources."
                : "Built options, popup and in-page React UI.",
    );
}

build().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
